namespace DeepExtensions.SourceGenerators;

partial class DeepExtensionsGenerator
{
    
    private void GenerateDeepCopy()
    {
        foreach (var cl in copyClassCollection?.Classes ?? [])
        {
            CreateDeepCopyClassFile(cl);
        }
    }

    private void CreateDeepCopyClassFile(INamedTypeSymbol cl)
    {
        string classNamespace = cl.ContainingNamespace?.ToDisplayString(FormatWithoutNullable) ?? string.Empty;
        bool hasLocalBaseClass = cl.BaseType != null && cl.BaseType.SpecialType != SpecialType.System_Object 
            && cl.BaseType.DeclaringSyntaxReferences.Length > 0; // check if in current assembly

        StringBuilder sb = new(
            $$"""
            // <auto-generated />

            #nullable enable annotations
            #nullable disable warnings

            // Suppress warnings about [Obsolete] member usage in generated code.
            #pragma warning disable CS0612, CS0618
            
            namespace {{classNamespace}};

            partial class {{cl.Name}} : IDeepCopy<{{cl.Name}}>
            {
                public {{(hasLocalBaseClass ? "override" : "virtual")}} {{cl.Name}} DeepCopy()
                {
                    var copy = new {{cl.Name}}();
                    DeepCopyTo(copy);
                    return copy;
                }

                protected void DeepCopyTo({{cl.Name}} target)
                {

            """);

        if (hasLocalBaseClass)
        {
            sb.AppendLine("        base.DeepCopyTo(target);");
        }

        var properties = cl.GetMembers().OfType<IPropertySymbol>();
        foreach (var prop in properties.Where(prop => !prop.GetAttributes().Any(a => SymbolEqualityComparer.Default.Equals(a.AttributeClass, DeepCopyIgnoreAttribute))))
        {
            TypeClass propType = ClassifyType(prop.Type);
            sb.Append("        ");
            sb.AppendLine(propType switch
            {
                TypeClass.ReferenceArray =>     $"target.{prop.Name} = DeepComparer.CopyItems(this.{prop.Name});",
                TypeClass.ValueArray =>         $"target.{prop.Name} = [.. this.{prop.Name}];",
                TypeClass.ReferenceList =>      $"target.{prop.Name} = [.. DeepComparer.CopyItems(this.{prop.Name})];",
                TypeClass.ValueList =>          $"target.{prop.Name} = [.. this.{prop.Name}];",
                TypeClass.Reference =>          $"target.{prop.Name} = this.{prop.Name}.DeepCopy();",
                TypeClass.NullableReference =>  $"target.{prop.Name} = this.{prop.Name}?.DeepCopy();",
                TypeClass.Value =>              $"target.{prop.Name} = this.{prop.Name};",
                _ =>                            $"// Unknown type for property {prop.Name}, manual handling may be required."
            });
        }

        sb.Append(
            """
                }
            }
            """);
        AddSource($"{cl.Name}DeepCopy.g.cs", sb.ToString());
    }
}
